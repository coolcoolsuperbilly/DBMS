-- ========== 1NF: ONE medicine per row, all atomic columns =============
-- Still redundant: patient, doctor, department and branch data repeat.
CREATE TABLE nf_demo.nf1_visit AS
SELECT r.appointment_id, r.patient_id, btrim(r.patient_name) AS patient_name,
       initcap(btrim(r.patient_city)) AS patient_city,
       r.branch_id, btrim(r.branch_location) AS branch_location,
       lower(btrim(r.branch_status)) AS branch_status,
       r.department_id, btrim(r.department_name) AS department_name,
       lower(btrim(r.department_status)) AS department_status,
       r.doctor_id, btrim(r.doctor_name) AS doctor_name,
       btrim(r.specialization) AS specialization,
       r.appointment_date, r.appointment_time, r.token_no,
       split_part(btrim(x.item), ':', 1)::INTEGER AS medicine_id,
       btrim(split_part(x.item, ':', 2)) AS medicine_name,
       btrim(split_part(x.item, ':', 3)) AS dosage,
       split_part(btrim(x.item), ':', 4)::INTEGER AS quantity
FROM nf_demo.raw_visit r
CROSS JOIN LATERAL unnest(string_to_array(r.medicine_list, '|')) AS x(item);

ALTER TABLE nf_demo.nf1_visit
    ADD PRIMARY KEY (appointment_id, medicine_id);

-- ========== 2NF: remove PARTIAL dependencies =========================
-- Old composite key: (appointment_id, medicine_id).
-- appointment_id -> appointment/patient/doctor/branch details
-- medicine_id -> medicine_name
-- (appointment_id,medicine_id) -> dosage,quantity
CREATE TABLE nf_demo.nf2_visit AS
SELECT DISTINCT appointment_id, patient_id, patient_name, patient_city,
       branch_id, branch_location, branch_status,
       department_id, department_name, department_status,
       doctor_id, doctor_name, specialization,
       appointment_date, appointment_time, token_no
FROM nf_demo.nf1_visit;
ALTER TABLE nf_demo.nf2_visit ADD PRIMARY KEY (appointment_id);

CREATE TABLE nf_demo.nf2_medicine AS
SELECT DISTINCT medicine_id, medicine_name FROM nf_demo.nf1_visit;
ALTER TABLE nf_demo.nf2_medicine ADD PRIMARY KEY (medicine_id);

CREATE TABLE nf_demo.nf2_visit_medicine AS
SELECT appointment_id, medicine_id, dosage, quantity FROM nf_demo.nf1_visit;
ALTER TABLE nf_demo.nf2_visit_medicine
    ADD PRIMARY KEY (appointment_id, medicine_id),
    ADD FOREIGN KEY (appointment_id) REFERENCES nf_demo.nf2_visit(appointment_id),
    ADD FOREIGN KEY (medicine_id) REFERENCES nf_demo.nf2_medicine(medicine_id);
-- In nf2_visit, doctor_id -> doctor_name and branch_id -> branch_location
-- are still TRANSITIVE dependencies, so 3NF is required.

-- ========== 3NF: remove TRANSITIVE dependencies =======================
CREATE TABLE nf_demo.nf3_patient AS
SELECT DISTINCT patient_id, patient_name AS name, patient_city AS city
FROM nf_demo.nf2_visit;
ALTER TABLE nf_demo.nf3_patient ADD PRIMARY KEY (patient_id);

CREATE TABLE nf_demo.nf3_branch AS
SELECT DISTINCT branch_id, branch_location AS location, branch_status AS status
FROM nf_demo.nf2_visit;
ALTER TABLE nf_demo.nf3_branch ADD PRIMARY KEY (branch_id);

CREATE TABLE nf_demo.nf3_department AS
SELECT DISTINCT department_id, department_name, branch_id,
       department_status AS status
FROM nf_demo.nf2_visit;
ALTER TABLE nf_demo.nf3_department
    ADD PRIMARY KEY (department_id),
    ADD FOREIGN KEY (branch_id) REFERENCES nf_demo.nf3_branch(branch_id);

CREATE TABLE nf_demo.nf3_doctor AS
SELECT DISTINCT doctor_id, doctor_name AS name, specialization, department_id
FROM nf_demo.nf2_visit;
ALTER TABLE nf_demo.nf3_doctor
    ADD PRIMARY KEY (doctor_id),
    ADD FOREIGN KEY (department_id) REFERENCES nf_demo.nf3_department(department_id);

CREATE TABLE nf_demo.nf3_appointment AS
SELECT appointment_id, patient_id, doctor_id, branch_id,
       appointment_date, appointment_time, token_no
FROM nf_demo.nf2_visit;
ALTER TABLE nf_demo.nf3_appointment
    ADD PRIMARY KEY (appointment_id),
    ADD FOREIGN KEY (patient_id) REFERENCES nf_demo.nf3_patient(patient_id),
    ADD FOREIGN KEY (doctor_id) REFERENCES nf_demo.nf3_doctor(doctor_id),
    ADD FOREIGN KEY (branch_id) REFERENCES nf_demo.nf3_branch(branch_id);

-- ========== BCNF: check candidate keys / determinants ================
-- BCNF requires every nontrivial functional determinant to be a superkey.
-- Each table above now has key-based FDs only, given the HMS business rules:
-- branch_id -> location,status
-- department_id -> department_name,branch_id,status
-- doctor_id -> name,specialization,department_id
-- patient_id -> name,city
-- appointment_id -> patient_id,doctor_id,branch_id,date,time,token_no
-- medicine_id -> medicine_name
-- (appointment_id,medicine_id) -> dosage,quantity
-- The FULL HMS schema has composite keys for room, doctor_shift,
-- prescription_detail, pharmacy_inventory, assignments, salary_shift_log.
-- Bill has two candidate keys: bill_id and NOT NULL UNIQUE appointment_id.
-- The project document therefore says no further BCNF split is required.

